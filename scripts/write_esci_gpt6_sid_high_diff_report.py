#!/usr/bin/env python3
"""Write a Markdown report from the GPT-6 Luna/SID-2 high diff CSV."""

from __future__ import annotations

import argparse
import csv
from collections import OrderedDict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "research/results/esci_gpt6_luna_sid2_high_diff.csv"
DEFAULT_OUTPUT = ROOT / "research/sid/esci_gpt6_luna_vs_sid2_high_threshold_diff.md"


def _escape(value: object) -> str:
    return (
        str(value or "")
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\r", "")
        .replace("\n", "<br>")
    )


def _number(value: str) -> float:
    return float(value)


def _grade(value: str) -> str:
    if not value or value.strip().lower() in {"na", "n/a", "nan"}:
        return "NA"
    try:
        return f"{float(value):g}"
    except ValueError:
        return _escape(value)


def _load_results(path: Path) -> list[tuple[dict[str, str], list[dict[str, str]]]]:
    by_query: OrderedDict[str, list[dict[str, str]]] = OrderedDict()
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        required = {
            "QueryID",
            "Query",
            "NDCGLHS",
            "NDCGRHS",
            "NDCGDiff",
            "MaxNDCG",
            "RankLHS",
            "DocIDLHS",
            "TitleLHS",
            "GradeLHS",
            "RankRHS",
            "DocIDRHS",
            "TitleRHS",
            "GradeRHS",
        }
        if not reader.fieldnames or not required.issubset(reader.fieldnames):
            raise ValueError(f"{path} must contain {', '.join(sorted(required))}.")
        for row in reader:
            by_query.setdefault(row["QueryID"], []).append(row)

    results = []
    for query_id, rows in by_query.items():
        rows.sort(key=lambda row: int(row["RankLHS"] or row["RankRHS"] or 0))
        first = rows[0]
        for row in rows[1:]:
            if (
                row["Query"] != first["Query"]
                or row["NDCGLHS"] != first["NDCGLHS"]
                or row["NDCGRHS"] != first["NDCGRHS"]
                or row["NDCGDiff"] != first["NDCGDiff"]
                or row["MaxNDCG"] != first["MaxNDCG"]
            ):
                raise ValueError(f"Inconsistent repeated query data for {query_id}.")
        results.append((first, rows))

    return sorted(
        results,
        key=lambda item: (-abs(_number(item[0]["NDCGDiff"])), int(item[0]["QueryID"])),
    )


def _english_query_ids() -> set[str]:
    from exps.datasets import get_dataset

    dataset = get_dataset("esci", ensure_snowball=False)
    locales = dataset.judgments.groupby("query_id")["product_locale"].agg(
        lambda values: set(values.dropna().astype(str))
    )
    return {
        str(query_id)
        for query_id, query_locales in locales.items()
        if query_locales == {"us"}
    }


def _top10_overlap(rows: list[dict[str, str]]) -> int:
    lhs = {row["DocIDLHS"] for row in rows if row["DocIDLHS"]}
    rhs = {row["DocIDRHS"] for row in rows if row["DocIDRHS"]}
    return len(lhs & rhs)


def _build_report(csv_path: Path) -> str:
    all_queries = _load_results(csv_path)
    english_query_ids = _english_query_ids()
    queries = [
        item for item in all_queries if item[0]["QueryID"] in english_query_ids
    ]
    if not queries:
        raise ValueError(f"No English-locale queries found in {csv_path}.")
    ndcg_lhs = [_number(first["NDCGLHS"]) for first, _ in queries]
    ndcg_rhs = [_number(first["NDCGRHS"]) for first, _ in queries]
    differences = [_number(first["NDCGDiff"]) for first, _ in queries]
    max_ndcg = [_number(first["MaxNDCG"]) for first, _ in queries]
    min_abs_diff = min(abs(delta) for delta in differences)
    lhs_name = "GPT-6 Luna · BM25 + E5"
    rhs_name = "SID-2 high · BM25 + E5"

    lines = [
        "# ESCI: GPT-6 Luna vs SID-2 high (BM25 + E5)",
        "",
        "> **Note:** This report was generated by an LLM.",
        "",
        "## Summary",
        "",
        f"The threshold-filtered CSV contains {len(all_queries):,} queries; this report "
        f"shows its **{len(queries):,} English-locale queries** only. ESCI identifies "
        "query locale through `product_locale`; this report keeps `us` and excludes "
        "other locales. The smallest included absolute NDCG difference is "
        f"{min_abs_diff:.4f}; the diff script defaults to a threshold of 0.1.",
        "",
        f"- Mean NDCG for the included queries: GPT-6 Luna **{sum(ndcg_lhs) / len(ndcg_lhs):.4f}**; "
        f"SID-2 high **{sum(ndcg_rhs) / len(ndcg_rhs):.4f}**.",
        f"- Mean NDCG difference (SID-2 minus GPT-6 Luna): "
        f"**{sum(differences) / len(differences):+.4f}**.",
        f"- Mean max NDCG (judgment ceiling) for these queries: "
        f"**{sum(max_ndcg) / len(max_ndcg):.4f}**.",
        "- Each query section compares the top results by rank; matching rank positions "
        "do not imply matching documents.",
        "- `NA` means the result has no explicit ESCI judgment. Grade 0 is an explicit "
        "nonrelevant label; evaluation treats unjudged results as zero relevance.",
        "",
        "### Queries above the threshold",
        "",
        f"| Query ID | Query | {lhs_name} NDCG | {rhs_name} NDCG | Max NDCG | "
        "SID − GPT-6 NDCG | Top-10 overlap |",
        "| ---: | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for first, rows in queries:
        lines.append(
            f"| {first['QueryID']} | {_escape(first['Query'])} | "
            f"{_number(first['NDCGLHS']):.4f} | {_number(first['NDCGRHS']):.4f} | "
            f"{_number(first['MaxNDCG']):.4f} | {_number(first['NDCGDiff']):+.4f} | "
            f"{_top10_overlap(rows)}/10 |"
        )

    lines.extend(
        [
            "",
            "## Query-by-query results",
            "",
            "The following sections include every query in the threshold-filtered CSV. "
            "Product IDs and ESCI grades are retained from that file.",
            "",
        ]
    )
    for first, rows in queries:
        lines.extend(
            [
                f"### Query {first['QueryID']}",
                "",
                f"> {_escape(first['Query'])}",
                "",
                f"NDCG: GPT-6 Luna **{_number(first['NDCGLHS']):.4f}**; "
                f"SID-2 high **{_number(first['NDCGRHS']):.4f}** "
                f"(SID − GPT-6: {_number(first['NDCGDiff']):+.4f}). "
                f"Max achievable NDCG from judgments: **{_number(first['MaxNDCG']):.4f}**.",
                "",
                f"| Rank LHS | Doc ID LHS | Title LHS ({lhs_name}) | Grade LHS | "
                f"Rank RHS | Doc ID RHS | Title RHS ({rhs_name}) | Grade RHS |",
                "| ---: | --- | --- | ---: | ---: | --- | --- | ---: |",
            ]
        )
        for row in rows:
            lines.append(
                f"| {row['RankLHS'] or '—'} | {_escape(row['DocIDLHS']) or '—'} | "
                f"{_escape(row['TitleLHS']) or '—'} | {_grade(row['GradeLHS'])} | "
                f"{row['RankRHS'] or '—'} | {_escape(row['DocIDRHS']) or '—'} | "
                f"{_escape(row['TitleRHS']) or '—'} | {_grade(row['GradeRHS'])} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Configuration and source data",
            "",
            "- GPT-6 Luna LHS: [`configs/ecom_agentic/"
            "agentic_ecom_2tools_e5_gpt6_luna.yml`](../../configs/ecom_agentic/"
            "agentic_ecom_2tools_e5_gpt6_luna.yml)",
            "- SID-2 high RHS: [`configs/ecom_sid/"
            "agentic_ecom_sid_bm25_e5_base_v2_high.yml`](../../configs/ecom_sid/"
            "agentic_ecom_sid_bm25_e5_base_v2_high.yml)",
            f"- Source CSV: [`{csv_path.name}`](../results/{csv_path.name})",
            "- Both variants use BM25 and E5-base-v2. The diff script prints all "
            "sampled queries and writes only those meeting the NDCG threshold.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    report = _build_report(args.input)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
