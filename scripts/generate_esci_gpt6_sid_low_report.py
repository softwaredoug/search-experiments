#!/usr/bin/env python3
"""Generate a query-by-query report from the cached 1,000-query ESCI matrix run."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
from cheat_at_search.data_dir import ensure_data_subdir
from cheat_at_search.search import run_strategy

from exps.datasets import get_dataset
from exps.strategy_factory import create_strategy, load_strategy
from exps.trace_utils import build_agentic_trace_root


ROOT = Path(__file__).resolve().parents[1]
STRATEGIES = (
    (
        "GPT-6 Luna · BM25 + E5",
        "configs/ecom_agentic/agentic_ecom_2tools_e5_gpt6_luna.yml",
    ),
    (
        "SID-2 · BM25 + E5 · low",
        "configs/ecom_sid/agentic_ecom_sid_bm25_e5_base_v2_low.yml",
    ),
)
BATCH_SIZE = 100


def _escape(value: object) -> str:
    text = "" if pd.isna(value) else str(value)
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", "<br>")


def _load_strategy(config_path: str, *, dataset, device: str, workers: int):
    config, params, _ = load_strategy(str(ROOT / config_path), device=device)
    trace_path = build_agentic_trace_root(
        config.name,
        "esci",
        run_started_at=(
            f"report_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S_%f')}"
        ),
    )
    strategy, _ = create_strategy(
        config,
        corpus=dataset.corpus,
        workers=workers,
        params=params,
        device=device,
        dataset="esci",
        trace_path=trace_path,
        judgments=dataset.judgments,
    )
    return config.name, strategy


def _assert_cache_available(strategy, queries: pd.DataFrame) -> None:
    cache_dir = Path(ensure_data_subdir("search_cache")) / str(strategy.cache_key)
    missing = []
    for batch_index, start in enumerate(range(0, len(queries), BATCH_SIZE)):
        batch = queries.iloc[start:start + BATCH_SIZE]
        cache_path = strategy._batch_cache_path(cache_dir, batch_index, batch)
        if cache_path is None or not cache_path.exists():
            missing.append(batch_index)
    if missing:
        raise RuntimeError(
            "Missing cached result batches for this ESCI matrix sample; "
            "refusing to trigger a fresh model run. Missing batch indexes: "
            + ", ".join(map(str, missing))
        )


def _rankings(graded: pd.DataFrame) -> dict[int, pd.DataFrame]:
    return {
        int(query_id): rows.sort_values("rank").head(10).copy()
        for query_id, rows in graded.groupby("query_id", sort=False)
    }


def _query_metrics(graded: pd.DataFrame) -> dict[int, dict[str, float]]:
    per_query = (
        graded.sort_values("rank")
        .drop_duplicates("query_id")
        .set_index("query_id")[["ndcg", "mrr", "max_ndcg"]]
    )
    return {
        int(query_id): {
            "ndcg": float(row["ndcg"]),
            "mrr": float(row["mrr"]),
            "max_ndcg": float(row["max_ndcg"]),
        }
        for query_id, row in per_query.iterrows()
    }


def _document_cell(row: pd.Series | None) -> str:
    if row is None:
        return "—"
    doc_id = _escape(row.get("doc_id", ""))
    title_value = row.get("title")
    if pd.isna(title_value) or not str(title_value).strip():
        title_value = row.get("product_title")
    if pd.isna(title_value) or not str(title_value).strip():
        title_value = "(untitled)"
    title = _escape(title_value)
    grade = row.get("grade", 0)
    try:
        grade_text = f"grade {float(grade):g}"
    except (TypeError, ValueError):
        grade_text = "grade —"
    return f"**{doc_id}** — {title} ({grade_text})"


def _write_report(
    output_path: Path,
    *,
    num_queries: int,
    seed: int,
    query_text: dict[int, str],
    rankings: list[dict[int, pd.DataFrame]],
    metrics: list[dict[int, dict[str, float]]],
) -> None:
    gpt_name, sid_name = (name for name, _ in STRATEGIES)
    query_ids = sorted(set(rankings[0]) & set(rankings[1]))
    different = [
        query_id
        for query_id in query_ids
        if rankings[0][query_id]["doc_id"].astype(str).tolist()
        != rankings[1][query_id]["doc_id"].astype(str).tolist()
    ]
    overlaps = {
        query_id: len(
            set(rankings[0][query_id]["doc_id"].astype(str))
            & set(rankings[1][query_id]["doc_id"].astype(str))
        )
        for query_id in query_ids
    }
    means = [
        {
            metric: sum(values[query_id][metric] for query_id in query_ids)
            / len(query_ids)
            for metric in ("ndcg", "mrr", "max_ndcg")
        }
        for values in metrics
    ]

    lines = [
        "# ESCI: GPT-6 Luna vs low-effort SID-2 (BM25 + E5)",
        "",
        "> **Note:** This report was generated by an LLM.",
        "> It compares cached ESCI evaluation results; it does not contain",
        "> examples from any training set.",
        "",
        "## Summary",
        "",
        f"This comparison covers {len(query_ids):,} queries from the ESCI "
        f"{num_queries:,}-query sample (seed {seed}). The sample matches the "
        "existing e-commerce SID matrix run. A query is listed as different "
        "when the ordered top-10 document IDs differ between variants.",
        "",
        f"- Different top-10 lists: **{len(different):,} / {len(query_ids):,}**",
        f"- Identical top-10 lists: **{len(query_ids) - len(different):,} / {len(query_ids):,}**",
        f"- Mean NDCG: GPT-6 Luna **{means[0]['ndcg']:.4f}**; SID-2 low **{means[1]['ndcg']:.4f}** "
        f"(SID − GPT-6: {means[1]['ndcg'] - means[0]['ndcg']:+.4f})",
        f"- Mean MRR: GPT-6 Luna **{means[0]['mrr']:.4f}**; SID-2 low **{means[1]['mrr']:.4f}** "
        f"(SID − GPT-6: {means[1]['mrr'] - means[0]['mrr']:+.4f})",
        f"- Mean max NDCG from available judgments: **{means[0]['max_ndcg']:.4f}**.",
        "",
        "The summary below lists every query with a different ordered top-10. "
        "The sections that follow show each variant's ranked products side by side. "
        "ESCI grades are the relevance labels; unjudged retrieved products are scored as grade 0.",
        "",
        "### Queries with different results",
        "",
        f"| Query ID | Query | {gpt_name} NDCG | {sid_name} NDCG | SID − GPT-6 NDCG | Top-10 overlap |",
        "| ---: | --- | ---: | ---: | ---: | ---: |",
    ]
    for query_id in different:
        gpt_ndcg = metrics[0][query_id]["ndcg"]
        sid_ndcg = metrics[1][query_id]["ndcg"]
        lines.append(
            f"| {query_id} | {_escape(query_text[query_id])} | {gpt_ndcg:.4f} | "
            f"{sid_ndcg:.4f} | {sid_ndcg - gpt_ndcg:+.4f} | {overlaps[query_id]}/10 |"
        )

    lines.extend(
        [
            "",
            "## Query-by-query results",
            "",
            "Only queries with different ordered top-10 document IDs are included. "
            "Rows align by rank, not by matching document. Grades of 0 are nonrelevant "
            "or unjudged under the dataset qrels.",
            "",
        ]
    )
    for query_id in different:
        gpt_metrics = metrics[0][query_id]
        sid_metrics = metrics[1][query_id]
        lines.extend(
            [
                f"### Query {query_id}",
                "",
                f"> {_escape(query_text[query_id])}",
                "",
                f"NDCG: GPT-6 Luna **{gpt_metrics['ndcg']:.4f}**; SID-2 low "
                f"**{sid_metrics['ndcg']:.4f}** ({sid_metrics['ndcg'] - gpt_metrics['ndcg']:+.4f}). "
                f"MRR: GPT-6 Luna **{gpt_metrics['mrr']:.4f}**; SID-2 low "
                f"**{sid_metrics['mrr']:.4f}** ({sid_metrics['mrr'] - gpt_metrics['mrr']:+.4f}). "
                f"Max NDCG: **{gpt_metrics['max_ndcg']:.4f}**.",
                "",
                f"| Rank | {gpt_name} | {sid_name} |",
                "| ---: | --- | --- |",
            ]
        )
        gpt_rows = rankings[0][query_id].to_dict("records")
        sid_rows = rankings[1][query_id].to_dict("records")
        for rank in range(10):
            gpt_row = gpt_rows[rank] if rank < len(gpt_rows) else None
            sid_row = sid_rows[rank] if rank < len(sid_rows) else None
            lines.append(
                f"| {rank + 1} | {_document_cell(pd.Series(gpt_row) if gpt_row else None)} "
                f"| {_document_cell(pd.Series(sid_row) if sid_row else None)} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Configuration and reproduction",
            "",
            f"- GPT-6 Luna: [`{STRATEGIES[0][1]}`](../../{STRATEGIES[0][1]})",
            f"- SID-2 low: [`{STRATEGIES[1][1]}`](../../{STRATEGIES[1][1]})",
            "- Both variants use BM25 and E5-base-v2; SID-2 uses low reasoning effort.",
            "- The full ESCI judgments contain 130,652 queries. This report uses the "
            "same 1,000-query sample and seed as the existing ESCI matrix because the "
            "full query set is substantially larger.",
            "- Run `uv run python scripts/generate_esci_gpt6_sid_low_report.py` to "
            "regenerate from the cached matrix sample. The generator verifies all "
            "cache batches before running and will not start fresh model calls.",
            "",
        ]
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "research/sid/esci_gpt6_luna_vs_sid2_low.md",
    )
    parser.add_argument("--num-queries", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", default="mps")
    parser.add_argument("--workers", type=int, default=24)
    args = parser.parse_args()

    dataset = get_dataset("esci", workers=args.workers, ensure_snowball=True)
    sampled_queries = (
        dataset.judgments[["query", "query_id"]]
        .drop_duplicates()
        .sample(frac=1, random_state=args.seed)
        .head(args.num_queries)
        .reset_index(drop=True)
    )
    built = [
        _load_strategy(
            config_path,
            dataset=dataset,
            device=args.device,
            workers=args.workers,
        )
        for _, config_path in STRATEGIES
    ]
    for _, strategy in built:
        _assert_cache_available(strategy, sampled_queries)

    graded_results = [
        run_strategy(
            strategy,
            dataset.judgments,
            num_queries=args.num_queries,
            seed=args.seed,
            batch_size=BATCH_SIZE,
            show_progress=False,
            cache=True,
        )
        for _, strategy in built
    ]
    rankings = [_rankings(graded) for graded in graded_results]
    metrics = [_query_metrics(graded) for graded in graded_results]
    query_text = {
        int(row.query_id): str(row.query)
        for row in sampled_queries.itertuples(index=False)
    }
    _write_report(
        args.output,
        num_queries=args.num_queries,
        seed=args.seed,
        query_text=query_text,
        rankings=rankings,
        metrics=metrics,
    )
    print(f"Wrote {args.output}")
    print(f"Compared {len(rankings[0])} queries.")


if __name__ == "__main__":
    main()
